#!/usr/bin/env node
/**
 * Dodaje ręczne opinie 5★ dla wybranego użytkownika (domyślnie 83).
 * Tworzy zamknięte deale z losowymi recenzentami, jeśli brak istniejących opinii.
 *
 * Użycie: node scripts/seed-user-reviews.mjs [revieweeId]
 */
import path from 'path';
import { fileURLToPath } from 'url';
import { PrismaClient } from '@prisma/client';
import { config } from 'dotenv';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
config({ path: path.join(__dirname, '..', '.env') });

const REVIEWEE_ID = Number(process.argv[2] || '83');
const REVIEW_COUNT = 2;
const SEED_SOURCE = 'ADMIN_PROFILE_SEED';

const COMMENTS = [
  'Profesjonalna obsługa od pierwszego kontaktu po finalizację transakcji. Łukasz z Sonar Nieruchomości prowadził sprawę sprawnie i z pełnym zaangażowaniem — polecam współpracę.',
  'Świetna komunikacja, terminowe prezentacje i pełne wsparcie na każdym etapie. Transakcja przebiegła bez stresu — zdecydowanie polecam tego agenta.',
];

function daysAgo(n) {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d;
}

function pickReviewers(allUsers, revieweeId, count) {
  const pool = allUsers
    .map((u) => u.id)
    .filter((id) => id !== revieweeId)
    .sort((a, b) => a - b);
  if (pool.length < count) {
    throw new Error(`Za mało użytkowników do opinii (potrzeba ${count}, jest ${pool.length}).`);
  }
  const step = Math.max(1, Math.floor(pool.length / (count + 2)));
  const picked = [];
  for (let i = 0; i < count; i += 1) {
    const idx = Math.min(pool.length - 1, (i + 1) * step + (i * 3));
    const id = pool[idx];
    if (!picked.includes(id)) picked.push(id);
  }
  let cursor = 0;
  while (picked.length < count && cursor < pool.length) {
    if (!picked.includes(pool[cursor])) picked.push(pool[cursor]);
    cursor += 1;
  }
  return picked.slice(0, count);
}

const prisma = new PrismaClient();

try {
  if (!Number.isFinite(REVIEWEE_ID) || REVIEWEE_ID <= 0) {
    throw new Error('Podaj poprawne ID użytkownika (reviewee).');
  }

  const reviewee = await prisma.user.findUnique({
    where: { id: REVIEWEE_ID },
    select: { id: true, name: true, email: true },
  });
  if (!reviewee) {
    throw new Error(`Brak użytkownika id=${REVIEWEE_ID}`);
  }

  const existing = await prisma.review.count({
    where: { revieweeId: REVIEWEE_ID, isAutoGenerated: false },
  });
  if (existing >= REVIEW_COUNT) {
    console.log(`Użytkownik ${REVIEWEE_ID} ma już ${existing} opinii ręcznych — pomijam.`);
    process.exit(0);
  }

  const offer = await prisma.offer.findFirst({
    where: { userId: REVIEWEE_ID },
    select: { id: true },
    orderBy: { id: 'desc' },
  });
  if (!offer) {
    throw new Error(`Użytkownik ${REVIEWEE_ID} nie ma oferty — potrzebna oferta do powiązania deala.`);
  }

  const allUsers = await prisma.user.findMany({
    select: { id: true },
    orderBy: { id: 'asc' },
    take: 200,
  });
  const reviewerIds = pickReviewers(allUsers, REVIEWEE_ID, REVIEW_COUNT);

  const created = [];
  for (let i = 0; i < reviewerIds.length; i += 1) {
    const reviewerId = reviewerIds[i];
    const already = await prisma.review.findFirst({
      where: { revieweeId: REVIEWEE_ID, reviewerId, isAutoGenerated: false },
    });
    if (already) {
      console.log(`Pomijam recenzenta ${reviewerId} — opinia już istnieje.`);
      continue;
    }

    let deal = await prisma.deal.findFirst({
      where: { offerId: offer.id, buyerId: reviewerId, sellerId: REVIEWEE_ID },
      select: { id: true },
    });
    if (!deal) {
      deal = await prisma.deal.create({
        data: {
          offerId: offer.id,
          buyerId: reviewerId,
          sellerId: REVIEWEE_ID,
          status: 'FINALIZED',
          isActive: false,
          finalizedAt: daysAgo(45 - i * 12),
        },
        select: { id: true },
      });
    }

    const review = await prisma.review.create({
      data: {
        dealId: deal.id,
        reviewerId,
        revieweeId: REVIEWEE_ID,
        rating: 5,
        comment: COMMENTS[i] || COMMENTS[0],
        isAutoGenerated: false,
        source: SEED_SOURCE,
        createdAt: daysAgo(40 - i * 10),
      },
    });
    created.push({ reviewId: review.id, reviewerId, dealId: deal.id });
  }

  console.log(`Dodano ${created.length} opinii dla użytkownika ${REVIEWEE_ID} (${reviewee.name || reviewee.email}):`);
  for (const row of created) {
    console.log(`  review #${row.reviewId} od user #${row.reviewerId} (deal #${row.dealId})`);
  }
} catch (error) {
  console.error(error?.message || error);
  process.exit(1);
} finally {
  await prisma.$disconnect();
}
